function EnableCustomPlayerTitles(hEntity)
if not hEntity or hEntity:IsNull() then return end
local playerId = hEntity:GetPlayerOwnerID()
if playerId == nil or playerId < 0 then return end
local steamAccountID = PlayerResource:GetSteamAccountID(playerId)
local data = customPlayerTitleData[steamAccountID]
if not data then return end
LinkLuaModifier(data.modifier, "modifiers/player/custom_player_titles", LUA_MODIFIER_MOTION_NONE)
if not hEntity:HasModifier(data.modifier) then
hEntity:AddNewModifier(hEntity, nil, data.modifier, {})
end
end
